fn md5(input: &[u8]) -> [u8; 16] {
    let mut state = [0x67452301u32, 0xefcdab89, 0x98badcfe, 0x10325476];
    let blocks = (input.len() + 9 + 63) / 64;
    for b in 0..blocks {
        let mut block = [0u8; 64];
        for i in 0..64 {
            let p = b * 64 + i;
            block[i] = if p < input.len() {
                input[p]
            } else if p == input.len() {
                0x80
            } else if p >= blocks * 64 - 8 {
                ((input.len() as u64 * 8) >> ((p - (blocks * 64 - 8)) * 8)) as u8
            } else {
                0
            };
        }
        let mut m = [0u32; 16];
        for i in 0..16 {
            m[i] = u32::from_le_bytes([
                block[i * 4],
                block[i * 4 + 1],
                block[i * 4 + 2],
                block[i * 4 + 3],
            ]);
        }
        let [mut a, mut c_b, mut c, mut d] = state;
        for i in 0..64 {
            let (f, g) = if i < 16 {
                ((c_b & c) | (!c_b & d), i)
            } else if i < 32 {
                ((d & c_b) | (!d & c), (5 * i + 1) % 16)
            } else if i < 48 {
                (c_b ^ c ^ d, (3 * i + 5) % 16)
            } else {
                (c ^ (c_b | !d), (7 * i) % 16)
            };
            let next = c_b.wrapping_add(
                a.wrapping_add(f)
                    .wrapping_add(K[i])
                    .wrapping_add(m[g])
                    .rotate_left(SH[i]),
            );
            a = d;
            d = c;
            c = c_b;
            c_b = next;
        }
        state[0] = state[0].wrapping_add(a);
        state[1] = state[1].wrapping_add(c_b);
        state[2] = state[2].wrapping_add(c);
        state[3] = state[3].wrapping_add(d);
    }
    let mut out = [0; 16];
    for i in 0..4 {
        out[i * 4..i * 4 + 4].copy_from_slice(&state[i].to_le_bytes());
    }
    out
}
